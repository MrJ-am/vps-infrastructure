"""Build selectable color fonts from the CURRENT TeX composition and original SVG.

Run from any directory. Normal HTML/LaTeX use requires no Python or network.
Maintenance dependencies: fonttools[woff], skia-pathops, uharfbuzz.
The limited TeX reader deliberately fails on unrecognized composition changes.
"""
from pathlib import Path
import base64
import hashlib
import json
import re
import xml.etree.ElementTree as ET

import pathops
import uharfbuzz as hb
from fontTools.fontBuilder import FontBuilder
from fontTools.colorLib.builder import buildCOLR, buildCPAL
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.qu2cuPen import Qu2CuPen
from fontTools.pens.t2CharStringPen import T2CharStringPen
from fontTools.svgLib.path import parse_path
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
UPM = 10000
FONT_PATH = ROOT / 'fonts/Parisienne-Regular.ttf'
font = TTFont(FONT_PATH)
glyphs = font.getGlyphSet()
units = font['head'].unitsPerEm
cmap = font.getBestCmap()
source = (ROOT / 'mrjam.sty').read_text()
original_palette = [(0, 0, 0, 1), (100/255, 194/255, 155/255, 1), (1, 1, 1, 1)]
palette = [original_palette[0], (0, 0, 0, 1), original_palette[2]]


def path_from_recording(recording, matrix=(1, 0, 0, 1, 0, 0)):
    p = pathops.Path()
    recording.replay(TransformPen(p.getPen(), matrix))
    return p


def svg_layers():
    root = ET.parse(ROOT / 'artwork/Echologo.svg').getroot()
    assert root.attrib['viewBox'] == '0 0 30 30'
    layers = []
    for node in root.iter():
        tag = node.tag.rsplit('}', 1)[-1]
        if tag not in ('circle', 'path'):
            continue
        assert 'transform' not in node.attrib and 'stroke' not in node.attrib
        rec = RecordingPen()
        if tag == 'circle':
            x, y, r = (float(node.attrib[k]) for k in ('cx', 'cy', 'r'))
            # Same SVG arc-to-cubic conversion for the PDF and both fonts.
            d = f'M{x-r},{y} a{r},{r} 0 1 0 {2*r},0 a{r},{r} 0 1 0 {-2*r},0 Z'
        else:
            d = node.attrib['d']
        parse_path(d, rec)
        color = 1 if node.attrib.get('fill') == '#64c29b' else 2
        layers.append((rec, color))
    assert len(layers) == 5
    return layers


def cubic_recording(rec, matrix):
    out = RecordingPen()
    rec.replay(TransformPen(Qu2CuPen(out, max_err=0.00001, all_cubic=True), matrix))
    return out


def pdf_path(rec):
    commands = []
    for op, pts in rec.value:
        values = ' '.join(f'{v:.9f}' for pt in pts for v in pt)
        commands.append({'moveTo': f'{values} m', 'lineTo': f'{values} l',
                         'curveTo': f'{values} c', 'closePath': 'h',
                         'endPath': ''}[op])
    return '\n'.join(commands) + '\nf'


def pdf_color(color):
    if color == 1:
        return r'\SignaturePointRGB rg'
    return ' '.join(f'{n:.9f}' for n in palette[color][:3]) + ' rg'


def write_echo_tex(layers):
    """A real PDF Type 3 period, not an imported PDF/SVG image."""
    g = font['glyf'][cmap[46]]
    diameter = min(g.xMax - g.xMin, g.yMax - g.yMin)
    left = (g.xMax + g.xMin - diameter) / 2
    bottom = (g.yMax + g.yMin - diameter) / 2
    scale = diameter / 30 / units
    content = []
    for rec, color in layers:
        content.append(pdf_color(color))
        content.append(pdf_path(cubic_recording(rec,
                       (scale, 0, 0, -scale, left/units, (bottom+diameter)/units))))
    # The source paths are in em; cm scales them to PDF big points at use time.
    tex = r'''% Generated by tools/build-web.py from artwork/Echologo.svg. Do not edit.
\NeedsTeXFormat{LaTeX2e}[2022-11-01]
\ProvidesExplPackage{echo-period}{2026/09/17}{1.0}{Echo logo as a Unicode period}
\RequirePackage{selectable-graphic}
\RequirePackage{signature-colors}
\RequirePackage{graphicx}
\cs_new_protected:Npn \__echo_literal:n #1 {
 \sys_if_engine_xetex:TF {\special{pdf:content~#1}} {
  \sys_if_engine_luatex:TF {\pdfextension literal {#1}} {\pdfliteral{#1}}
 }
}
\NewDocumentCommand \EchoPeriod {} {
 \SignatureResolvePointColor
 \SelectableGraphic[colored=true]{.}{
  \hbox{
   \cs_set:Npx \__echo_em: {\dim_to_decimal_in_bp:n{1em}\c_space_tl}
   \__echo_literal:n {q~\__echo_em:~0~0~\__echo_em:~0~0~cm~
PATH
   ~Q}
   \rule[DEPTHem]{0pt}{TOTALem}\kernWIDTHem
  }
 }
}
\endinput
'''
    tex = tex.replace('PATH', ('\n'.join(content)+'\n').replace(' ', '~').replace('\n', '~\n'))
    tex = tex.replace('DEPTH', f'{min(0,g.yMin)/units:.12f}')
    tex = tex.replace('TOTAL', f'{(max(0,g.yMax)-min(0,g.yMin))/units:.12f}')
    tex = tex.replace('WIDTH', f'{font["hmtx"].metrics[cmap[46]][0]/units:.12f}')
    (ROOT / 'echo-period.sty').write_text(tex)
    return left, bottom, diameter


def rectangle(x0, y0, x1, y1):
    p = pathops.Path()
    p.moveTo(x0,y0); p.lineTo(x1,y0); p.lineTo(x1,y1); p.lineTo(x0,y1); p.close()
    return p


def combine(paths):
    out = pathops.Path()
    for p in paths:
        out.addPath(p)
    return pathops.simplify(out)


def make_font(name, filename, characters, cells, colored_layers, ascent, descent):
    order = ['.notdef']
    metrics = {'.notdef': (UPM//2, 0)}
    charstrings = {}
    colr = {}
    charmap = {}
    programs = []

    def add_glyph(gname, path, width):
        pen = T2CharStringPen(width, None, roundTolerance=0)
        path.draw(Qu2CuPen(pen, max_err=.0001, all_cubic=True))
        charstrings[gname] = pen.getCharString()
        metrics[gname] = (round(width), round(path.bounds[0]) if path else 0)
        if gname not in order:
            order.append(gname)

    add_glyph('.notdef', pathops.Path(), UPM//2)
    for character, (offset, width, overlap) in zip(characters, cells):
        gname = 'period' if character == '.' else character
        charmap[ord(character)] = gname
        cut = rectangle(offset-overlap, -UPM*2, offset+width+overlap, UPM*2)
        pieces = []
        for index, (path, color) in enumerate(colored_layers):
            piece = pathops.op(path, cut, pathops.PathOp.INTERSECTION)
            if not piece:
                continue
            piece = piece.transform(1,0,0,1,-offset,0)
            layername = f'{gname}.layer{index}'
            add_glyph(layername, piece, width)
            pieces.append((layername, color, piece))
        # Useful monochrome fallback: white motifs become holes in the circle.
        fallback = pathops.Path()
        for _, color, piece in pieces:
            fallback = pathops.op(fallback, piece,
                       pathops.PathOp.DIFFERENCE if color == 2 else pathops.PathOp.UNION)
        add_glyph(gname, fallback, width)
        colr[gname] = [(n,c) for n,c,_ in pieces]
        program=[]
        s=1000/(ascent+descent)
        for _,color,piece in pieces:
            rec=RecordingPen();piece.draw(rec)
            program.append(pdf_color(color))
            program.append(pdf_path(cubic_recording(rec,(s,0,0,s,0,descent*s))))
        programs.append('\n'.join(program))
    fb = FontBuilder(UPM, isTTF=False)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(charmap)
    fb.setupCFF(name, {'FullName': name, 'FamilyName': name,
        'Weight': 'Regular', 'version': '1.0',
        'Notice': 'Derived from Parisienne (SIL OFL 1.1); Echo artwork supplied by the user.'}, charstrings, {})
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=round(ascent), descent=-round(descent))
    fb.setupNameTable({'familyName':name,'styleName':'Regular','uniqueFontIdentifier':name+'-1.0',
        'fullName':name,'psName':name,'version':'Version 1.0',
        'licenseDescription':'SIL Open Font License 1.1; see Parisienne-OFL.txt.',
        'licenseInfoURL':'https://openfontlicense.org'})
    fb.setupOS2(version=4,sTypoAscender=round(ascent),sTypoDescender=-round(descent),sTypoLineGap=0,
        usWinAscent=round(ascent),usWinDescent=round(descent),fsSelection=0xC0)
    fb.setupPost()
    fb.font['COLR'] = buildCOLR(colr, version=0, glyphMap=fb.font.getReverseGlyphMap())
    fb.font['CPAL'] = buildCPAL([palette, original_palette])
    # Stable artifacts for unchanged sources.
    fb.font['head'].created = fb.font['head'].modified = 3872448000
    fb.font.recalcTimestamp = False
    fb.save(ROOT / 'fonts' / (filename+'.otf'))
    fb.font.flavor = 'woff2'
    fb.save(ROOT / 'web' / (filename+'.woff2'))
    return programs


def main():
    layers = svg_layers()
    left,bottom,diameter = write_echo_tex(layers)
    # Parse only the documented composition grammar; never silently approximate
    # an arbitrary TeX program. Positions stay authored in the existing TeX file.
    specs = re.findall(r'\\lettre\{([^}]+)\}\{([^}]+)\}\{(\\scalebox\{[^}]+\}\{[^}]+\}|\\grandpoint|[^}]+)\}', source)
    assert len(specs) == 5 and [x[2] for x in specs] == ['M', r'\scalebox{.7}{r}', 'J', r'\grandpoint', 'am'], 'Review unsupported TeX composition'
    # The selection margin follows the signature's em geometry.
    margin = float(re.search(r'margin-left=([\d.]+)em',source)[1])
    # Geometry is expressed in em; TeX chooses the scale at use time.
    assert r'\fontsize' not in source, 'MrJam must inherit the surrounding font size'
    depth,total,width = map(float,re.search(r'\\rule\[(-?[\d.]+)em\]\{0pt\}\{([\d.]+)em\}\\kern([\d.]+)em',source).groups())
    weights = list(map(float,re.search(r'weights=\{([^}]+)\}',source)[1].split(',')))
    point_raise,point_scale = map(float,re.search(r'\\newcommand\{\\grandpoint\}\{\\raisebox\{([\d.]+)em\}\{\\scalebox\{([\d.]+)\}',source).groups())
    hbf = hb.Font(hb.Face(FONT_PATH.read_bytes()))
    visual = []
    ordinary = []
    for x,y,text in specs:
        x,y = (float(x)+margin)*UPM,float(y)*UPM
        if text == r'\grandpoint':
            s=point_scale*diameter/30/units*UPM
            dx=x+point_scale*left/units*UPM
            dy=y+point_raise*UPM+point_scale*(bottom+diameter)/units*UPM
            visual.extend((path_from_recording(rec,(s,0,0,-s,dx,dy)),color) for rec,color in layers)
            continue
        scale = 1
        if text.startswith('\\scalebox'):
            scale,text = re.match(r'\\scalebox\{([^}]+)\}\{([^}]+)\}',text).groups()
            scale=float(scale)
        b=hb.Buffer();b.add_str(text);b.guess_segment_properties();hb.shape(hbf,b)
        for info,pos in zip(b.glyph_infos,b.glyph_positions):
            rec=RecordingPen();glyphs[font.getGlyphName(info.codepoint)].draw(rec)
            s=scale*UPM/units
            ordinary.append(path_from_recording(rec,(s,0,0,s,x+pos.x_offset*s,y+pos.y_offset*s)))
            x+=pos.x_advance*s; y+=pos.y_advance*s
    visual.insert(0,(combine(ordinary),0))
    cells=[];offset=0
    for weight in weights:
        advance=(width+margin)*UPM*weight/sum(weights)
        assert abs(round(advance)-advance)<1e-6, 'Use a UPM with exact advance widths'
        cells.append((offset,advance,.003*total*UPM))
        offset+=advance
    programs=make_font('MrJamSignature','MrJamSignature','MrJ.am',cells,visual,(total+depth)*UPM,-depth*UPM)
    tex=r'''% Generated vector glyphs. Run python tools/build-web.py after source changes.
\NeedsTeXFormat{LaTeX2e}[2022-11-01]
\ProvidesExplPackage{mrjam-glyphs}{2026/09/17}{1.0}{Shared PDF and HTML glyph contours}
\RequirePackage{signature-colors}
\cs_new_protected:Npn \MrJamGlyphCheck {
 \SignatureResolvePointColor
 \str_if_eq:eeF {\file_mdfive_hash:n{mrjam.sty}} {HASH} {
  \PackageError{mrjam}{Generated~glyphs~are~out~of~date}
   {Run~python~tools/build-web.py~before~compiling.}
 }
}
\NewExpandableDocumentCommand \MrJamGlyphData {m} {
 \int_case:nn {#1} {
CASES
 }
}
\endinput
'''
    cases='\n'.join('{'+str(i)+'}{'+(program+'\n').replace(' ','~').replace('\n','~\n')+'}' for i,program in enumerate(programs,1))
    (ROOT/'mrjam-glyphs.sty').write_text(tex.replace('HASH',hashlib.md5(source.encode()).hexdigest().upper()).replace('CASES',cases))
    # The independently usable Unicode period retains the original font metrics.
    s=diameter/30/units*UPM
    dot_layers=[(path_from_recording(rec,(s,0,0,-s,left/units*UPM,(bottom+diameter)/units*UPM)),c) for rec,c in layers]
    advance=font['hmtx'].metrics[cmap[46]][0]/units*UPM
    make_font('EchoPoint','EchoPoint','.',[(0,round(advance),0)],dot_layers,135/units*UPM,10/units*UPM)
    css = '''/* Generated from the current TeX composition; no JavaScript required. */
@font-face{font-family:MrJamSignature;src:url("MrJamSignature.woff2") format("woff2");font-display:block}
@font-face{font-family:EchoPoint;src:url("EchoPoint.woff2") format("woff2");font-display:block}
@font-palette-values --echo-green{font-family:MrJamSignature,EchoPoint;base-palette:1}
.mrjam,.echo-point{font-palette:var(--signature-palette,normal)}
.mrjam{font-family:MrJamSignature,serif;font-size:var(--signature-size,100px);font-weight:400;font-style:normal;font-synthesis:none;text-rendering:geometricPrecision;font-kerning:none;font-variant-ligatures:none;letter-spacing:0;word-spacing:0;text-transform:none;white-space:nowrap;direction:ltr;unicode-bidi:isolate;display:inline-block;line-height:HEIGHT;vertical-align:baseline;color:#000;user-select:text;-webkit-user-select:text}
.echo-point{line-height:.12;vertical-align:middle;font-family:EchoPoint,serif;font-weight:400;font-style:normal;font-synthesis:none}
'''.replace('HEIGHT',str(total))
    (ROOT/'web/signature.css').write_text(css)
    template = '''<!doctype html>
<html lang="fr"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>MrJ.am — signature sélectionnable</title><style>CSS
body{margin:32px;font:16px/1.6 system-ui;background:#fff;color:#222}main{max-width:900px;margin:auto}h1{font-size:22px}section{margin:28px 0}textarea{display:block;width:95%;min-height:65px;font:18px system-ui;padding:10px}code{font-size:14px} .sample{overflow:auto;padding:12px 5px} .muted{color:#555}
</style><main><h1>Signature MrJ.am</h1><p>Sélectionnez la signature, puis copiez-collez-la dans le champ ci-dessous.</p>
<div class="sample"><span class="mrjam" id="signature">MrJ.am</span></div>
<textarea aria-label="Zone de collage" placeholder="Coller ici"></textarea>
<section><p>En ligne : <span class="mrjam" style="--signature-size:32px">MrJ.am</span></p>
<p>Le point seul : <span class="echo-point" style="font-size:160px">.</span></p></section>
<p class="muted">Le texte copié est MrJ.am. Le point est le caractère ordinaire U+002E. L'apparence est portée par une fonte vectorielle. Le point est noir par défaut ; le vert d'origine reste disponible dans la palette --echo-green.</p>
<p>Intégration : <code>&lt;span class="mrjam"&gt;MrJ.am&lt;/span&gt;</code>, avec signature.css et les fontes WOFF2.</p></main></html>
'''
    (ROOT/'web/index.html').write_text(template.replace('CSS','@import url("signature.css");'))
    embedded=css
    for file in ('MrJamSignature','EchoPoint'):
        b64=base64.b64encode((ROOT/'web'/f'{file}.woff2').read_bytes()).decode()
        embedded=embedded.replace(f'url("{file}.woff2")',f'url("data:font/woff2;base64,{b64}")')
    (ROOT/'signature-autonome.html').write_text(template.replace('CSS',embedded))
    manifest={'source_sha256':hashlib.sha256(source.encode()).hexdigest(),
        'font_sha256':hashlib.sha256(FONT_PATH.read_bytes()).hexdigest(),
        'svg_sha256':hashlib.sha256((ROOT/'artwork/Echologo.svg').read_bytes()).hexdigest(),
        'positions':specs,'selection_weights':weights,'margin_em':margin,
        'width_em':width,'depth_em':-depth,'height_em':total+depth,
        'dot_original_bbox_units':[20,-10,166,135],
        'dot_new_bbox_units':[left,bottom,left+diameter,bottom+diameter],
        'dot_diameter_pt_at_100pt':point_scale*diameter/units*100}
    (ROOT/'web/geometry.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(manifest,ensure_ascii=False,indent=2))


if __name__ == '__main__':
    main()
